"""L1 box parsing and prompt building for WeVisOne-VL (CPU, no weights).

``parse_seg_boxes`` mirrors the reference text parser
(``extra_repos/WeVisOne-VL/wevisone_vl/engine.py``); ``parse_seg_boxes_from_ids``
rebuilds the same boxes in the connector process, where no tokenizer vocabulary
is available. Golden values are the matting fixture in
``customs/wevisone/golden/matting``, generated by ``customs/wevisone/ref_golden.py``.
"""

from __future__ import annotations

import pytest

from vllm_omni.model_executor.models.wevisone import constants

pytestmark = [pytest.mark.core_model, pytest.mark.cpu]

GOLDEN_RESPONSE = "<ref>the person</ref><box><9><65><753><1000><OBJ></box>"
GOLDEN_BOXES = [[0.009, 0.065, 0.753, 1.0]]
GOLDEN_COORDS = [9, 65, 753, 1000]
GOLDEN_SEG_TOKEN_ID = 152678
GOLDEN_COORD_BASE = 151669


def _generated_ids(coords, seg_id: int = GOLDEN_SEG_TOKEN_ID) -> list[int]:
    """One box span in generation order: open, coordinates, ``<OBJ>``, close, eos."""
    base = constants.coord_token_id_base(seg_id)
    return (
        [constants.BOX_OPEN_TOKEN_ID_FALLBACK]
        + [base + int(coord) for coord in coords]
        + [int(seg_id), constants.BOX_CLOSE_TOKEN_ID_FALLBACK, constants.EOS_TOKEN_ID_FALLBACK]
    )


def test_text_parser_matches_the_golden_fixture():
    assert constants.parse_seg_boxes(GOLDEN_RESPONSE) == GOLDEN_BOXES


def test_id_parser_reproduces_the_text_parser():
    assert constants.parse_seg_boxes_from_ids(_generated_ids(GOLDEN_COORDS)) == GOLDEN_BOXES


def test_coord_block_is_derived_from_the_seg_token_id():
    """The ``<0>..<1000>`` block starts nine ids below ``<OBJ>`` in the shipped tokenizer."""
    assert constants.coord_token_id_base(GOLDEN_SEG_TOKEN_ID) == GOLDEN_COORD_BASE
    assert constants.coord_token_id_base() == constants.COORD_TOKEN_ID_BASE_FALLBACK


def test_only_generated_tokens_are_scanned():
    """A ``visual_prompt`` request can carry a box span in its prompt.

    The reference parses boxes from the response alone, so scanning the whole
    sequence must not invent an extra mask for the reference box.
    """
    prompt_box = [100, 100, 500, 500]
    base = constants.coord_token_id_base(GOLDEN_SEG_TOKEN_ID)
    prompt_ids = [constants.BOX_OPEN_TOKEN_ID_FALLBACK]
    prompt_ids += [base + coord for coord in prompt_box]
    prompt_ids += [GOLDEN_SEG_TOKEN_ID, constants.BOX_CLOSE_TOKEN_ID_FALLBACK]

    generated = _generated_ids(GOLDEN_COORDS)

    # Whole-sequence scanning would also pick up the prompt span; the contract is
    # that generated-only scanning equals parsing the response text alone.
    assert constants.parse_seg_boxes_from_ids(prompt_ids + generated) == [
        [0.1, 0.1, 0.5, 0.5],
        GOLDEN_BOXES[0],
    ]
    assert constants.parse_seg_boxes_from_ids(generated) == GOLDEN_BOXES
    # A prompt box that is closed before any <OBJ> is not a query row at all.
    assert (
        constants.parse_seg_boxes_from_ids(
            [constants.BOX_OPEN_TOKEN_ID_FALLBACK]
            + [base + coord for coord in prompt_box]
            + [constants.BOX_CLOSE_TOKEN_ID_FALLBACK, GOLDEN_SEG_TOKEN_ID]
        )
        == []
    )


def test_generation_stops_at_eos():
    """Tokens after ``<|im_end|>`` are not part of the response."""
    trailing = [constants.BOX_OPEN_TOKEN_ID_FALLBACK, constants.COORD_TOKEN_ID_BASE_FALLBACK + 5, GOLDEN_SEG_TOKEN_ID]
    ids = _generated_ids(GOLDEN_COORDS) + trailing
    assert constants.parse_seg_boxes_from_ids(ids) == GOLDEN_BOXES


def test_degenerate_and_out_of_range_boxes_are_dropped():
    reversed_box = "<box><900><10><100><500><OBJ></box>"
    out_of_range = "<box><1001><10><1001><500><OBJ></box>"
    too_short = "<box><100><200><OBJ></box>"

    assert constants.parse_seg_boxes(reversed_box) == []
    assert constants.parse_seg_boxes(out_of_range) == []
    assert constants.parse_seg_boxes(too_short) == []

    for coords in ([900, 10, 100, 500], [1001, 10, 1001, 500], [100, 200]):
        assert constants.parse_seg_boxes_from_ids(_generated_ids(coords)) == []


def test_box_without_obj_does_not_produce_a_mask():
    """Masks exist only for ``<OBJ>`` tokens; a bare box span is not a query."""
    assert constants.parse_seg_boxes("<box><100><100><500><500></box>") == []
    ids = [constants.BOX_OPEN_TOKEN_ID_FALLBACK]
    base = constants.coord_token_id_base(GOLDEN_SEG_TOKEN_ID)
    ids += [base + c for c in (100, 100, 500, 500)]
    ids += [constants.BOX_CLOSE_TOKEN_ID_FALLBACK, constants.EOS_TOKEN_ID_FALLBACK]
    assert constants.parse_seg_boxes_from_ids(ids) == []


def test_multiple_boxes_are_ordered_by_query():
    response = "<box><10><10><200><200><OBJ></box><box><300><300><900><900><OBJ></box>"
    ids = _generated_ids([10, 10, 200, 200])[:-1] + _generated_ids([300, 300, 900, 900])
    expected = [[0.01, 0.01, 0.2, 0.2], [0.3, 0.3, 0.9, 0.9]]
    assert constants.parse_seg_boxes(response) == expected
    assert constants.parse_seg_boxes_from_ids(ids) == expected


@pytest.mark.parametrize(
    ("task", "query", "expected"),
    [
        ("detection", "person", "Locate all the instances that match the following description: person."),
        ("detection", "person\ncar", "Locate all the instances that match the following description: person. car."),
        ("referring", "the person", "Locate the instances that match the following description: the person."),
        ("point", "person", "point to: person"),
        ("count_box", "people", "How many people in the image? Please count them with boxes."),
        ("count_box", "", "How many objects in the image? Please count them with boxes."),
        ("count_point", "people", "How many people in the image?"),
        (
            "matting",
            "the person",
            "Locate the instances that match the following description and provide the alpha mattes: the person.",
        ),
        ("ocr", "", "detect all the word in the box format"),
        ("ocr_grounding", "hello", "Locate the following text in the image: hello"),
        ("freeform", "what is this?", "what is this?"),
    ],
)
def test_task_instructions_match_the_reference_family(task, query, expected):
    assert constants.build_prompt(task, query) == expected


def test_visual_prompt_instruction_encodes_reference_boxes():
    instruction = constants.build_prompt(
        "visual_prompt", reference_boxes=[[100, 100, 500, 500]], image_size=(1000, 1000)
    )
    assert instruction == (
        "Locate all similar objects in the image based on the reference boxes: "
        "<ref>object 1</ref><box><100><100><500><500></box>"
    )


def test_reference_box_bins_are_clamped_and_incomplete_boxes_skipped():
    instruction = constants.build_prompt(
        "visual_prompt",
        reference_boxes=[[1500, 0, 1200, 1000], [1, 2, 3]],
        image_size=(1000, 1000),
    )
    assert "<1000><0><1000><1000>" in instruction
    # A box with fewer than four values and an unknown image size contributes nothing.
    assert "<box></box>" in constants.build_prompt("visual_prompt", reference_boxes=[[1, 2, 3]], image_size=(0, 0))


def test_unknown_task_is_rejected():
    with pytest.raises(ValueError, match="unknown task 'masking'"):
        constants.build_prompt("masking", "the person")


def test_seg_token_id_is_resolved_from_the_tokenizer():
    class _StubTokenizer:
        def get_vocab(self):
            return {"<OBJ>": GOLDEN_SEG_TOKEN_ID, "<box>": constants.BOX_OPEN_TOKEN_ID_FALLBACK}

    assert constants.seg_token_id(_StubTokenizer()) == GOLDEN_SEG_TOKEN_ID
    assert constants.coord_token_id_base(constants.seg_token_id(_StubTokenizer())) == GOLDEN_COORD_BASE

    class _NoSegTokenizer:
        def get_vocab(self):
            return {"hello": 1}

    with pytest.raises(ValueError, match="missing from the tokenizer vocabulary"):
        constants.seg_token_id(_NoSegTokenizer())


def test_fallbacks_are_the_shipped_tokenizer_values():
    """Values verified against ``extra_repos/WeVisOne-VL-4B/tokenizer.json``."""
    assert constants.SEG_TOKEN_ID_FALLBACK == GOLDEN_SEG_TOKEN_ID
    assert constants.COORD_TOKEN_ID_BASE_FALLBACK == GOLDEN_COORD_BASE
    assert constants.EOS_TOKEN_ID_FALLBACK == 151645
